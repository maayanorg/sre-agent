'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { createShopProxy } = require('../workload/frontend/shop-proxy.cjs');
test('shop scripts parse', () => {
  const html = fs.readFileSync(path.join(__dirname, '../workload/frontend/shop.html'), 'utf8');
  for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) assert.doesNotThrow(() => new vm.Script(match[1]));
});
test('shop proxy enforces routes, methods, same origin and bounded bodies', async context => {
  let calls = 0;
  const server = http.createServer(createShopProxy(async ({ body }) => { calls++; return { status: 200, body: body || { products: [] } }; }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  context.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const checkout = (origin, body = '{}') => fetch(`${base}/api/shop/checkout`, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body });
  assert.equal((await checkout('https://attacker.invalid')).status, 403);
  assert.equal((await checkout('null')).status, 403);
  assert.equal((await fetch(`${base}/api/shop/checkout`)).status, 405);
  assert.equal((await fetch(`${base}/api/shop/execute`)).status, 404);
  assert.equal((await checkout(base, 'x'.repeat(9000))).status, 400);
  assert.equal(calls, 0);
  assert.equal((await checkout(base)).status, 200);
  assert.equal(calls, 1);
});
test('demo budgets limit checkout and requests, then reset after a minute', async context => {
  let time = 0, calls = 0;
  const server = http.createServer(createShopProxy(async () => { calls++; return { status: 200, body: {} }; }, { maxRequests: 3, maxCheckouts: 1, now: () => time }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  context.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const checkout = () => fetch(`${base}/api/shop/checkout`, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal((await checkout()).status, 200);
  const limited = await checkout();
  assert.equal(limited.status, 429);
  assert.equal(limited.headers.get('retry-after'), '60');
  assert.equal((await fetch(`${base}/api/shop/catalog`)).status, 200);
  assert.equal((await fetch(`${base}/api/shop/media`)).status, 200);
  assert.equal((await fetch(`${base}/api/shop/catalog`)).status, 429);
  assert.equal(calls, 3);
  time = 60000;
  assert.equal((await checkout()).status, 200);
});
test('concurrent request slots are released after transport failure', async context => {
  let rejectRequest, started;
  const entered = new Promise(resolve => { started = resolve; });
  const server = http.createServer(createShopProxy(() => { started(); return new Promise((resolve, reject) => { rejectRequest = reject; }); }, { maxConcurrent: 1 }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  context.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const url = `http://127.0.0.1:${server.address().port}/api/shop/catalog`;
  const first = fetch(url);
  await entered;
  assert.equal((await fetch(url)).status, 429);
  rejectRequest(new Error('Dependency unavailable'));
  assert.equal((await first).status, 503);
  const next = fetch(url);
  await new Promise(resolve => server.once('request', resolve));
  rejectRequest(new Error('Dependency unavailable'));
  assert.equal((await next).status, 503);
});